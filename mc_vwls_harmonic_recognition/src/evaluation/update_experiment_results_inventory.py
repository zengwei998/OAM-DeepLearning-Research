def stage(
    message: str,
) -> None:
    print(
        message,
        flush=True,
    )


def sha256_file(
    path: Path,
    *,
    chunk_size: int = 1024 * 1024,
) -> str:
    digest = hashlib.sha256()

    with path.open(
        "rb"
    ) as file_handle:
        while True:
            chunk = file_handle.read(
                chunk_size
            )

            if not chunk:
                break

            digest.update(
                chunk
            )

    return digest.hexdigest()


def human_readable_size(
    size_bytes: int,
) -> str:
    value = float(
        size_bytes
    )

    units = (
        "B",
        "KiB",
        "MiB",
        "GiB",
        "TiB",
    )

    unit_index = 0

    while (
        value >= 1024.0
        and unit_index
        < len(
            units
        )
        - 1
    ):
        value /= 1024.0
        unit_index += 1

    return (
        f"{value:.3f} "
        f"{units[unit_index]}"
    )


def count_csv_rows(
    path: Path,
) -> int | None:
    if path.suffix.lower() != ".csv":
        return None

    with path.open(
        "r",
        encoding="utf-8-sig",
        newline="",
    ) as csv_file:
        reader = csv.reader(
            csv_file
        )

        row_count = sum(
            1
            for _ in reader
        )

    return max(
        row_count - 1,
        0,
    )


def inspect_output(
    expected: ExpectedOutput,
) -> Dict[str, object]:
    path = (
        ROOT
        / expected.relative_path
    )

    exists = path.exists()
    is_file = path.is_file()

    if exists and is_file:
        stat = path.stat()

        size_bytes = int(
            stat.st_size
        )

        modified_time = datetime.fromtimestamp(
            stat.st_mtime
        ).isoformat(
            timespec="seconds"
        )

        file_hash = sha256_file(
            path
        )

        csv_rows = count_csv_rows(
            path
        )

        status = (
            "PASS"
            if size_bytes > 0
            else "EMPTY"
        )
    else:
        size_bytes = 0
        modified_time = ""
        file_hash = ""
        csv_rows = None

        status = (
            "MISSING_REQUIRED"
            if expected.required
            else "MISSING_OPTIONAL"
        )

    return {
        "category": expected.category,
        "relative_path": expected.relative_path,
        "description": expected.description,
        "required": int(
            expected.required
        ),
        "exists": int(
            exists
        ),
        "is_file": int(
            is_file
        ),
        "status": status,
        "size_bytes": size_bytes,
        "size_display": human_readable_size(
            size_bytes
        ),
        "csv_data_rows": (
            ""
            if csv_rows is None
            else csv_rows
        ),
        "modified_time": modified_time,
        "sha256": file_hash,
    }


def discover_additional_outputs(
    inventoried_paths: set[str],
) -> List[Dict[str, object]]:
    discovered: List[
        Dict[str, object]
    ] = []

    search_roots = (
        ROOT
        / "results"
        / "csv",
        ROOT
        / "results"
        / "figures",
        ROOT
        / "results"
        / "validation",
        ROOT
        / "results"
        / "tables",
    )

    for search_root in search_roots:
        if not search_root.exists():
            continue

        for path in sorted(
            search_root.rglob(
                "*"
            )
        ):
            if not path.is_file():
                continue

            relative_path = path.relative_to(
                ROOT
            ).as_posix()

            if relative_path in inventoried_paths:
                continue

            stat = path.stat()

            size_bytes = int(
                stat.st_size
            )

            csv_rows = count_csv_rows(
                path
            )

            discovered.append(
                {
                    "category": "additional",
                    "relative_path": relative_path,
                    "description": (
                        "Additional generated experiment output"
                    ),
                    "required": 0,
                    "exists": 1,
                    "is_file": 1,
                    "status": (
                        "PASS"
                        if size_bytes > 0
                        else "EMPTY"
                    ),
                    "size_bytes": size_bytes,
                    "size_display": human_readable_size(
                        size_bytes
                    ),
                    "csv_data_rows": (
                        ""
                        if csv_rows is None
                        else csv_rows
                    ),
                    "modified_time": (
                        datetime.fromtimestamp(
                            stat.st_mtime
                        ).isoformat(
                            timespec="seconds"
                        )
                    ),
                    "sha256": sha256_file(
                        path
                    ),
                }
            )

    return discovered


def save_inventory_csv(
    rows: Sequence[Dict[str, object]],
) -> None:
    INVENTORY_CSV_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    if not rows:
        raise ValueError(
            "Inventory is empty."
        )

    fieldnames = list(
        rows[0].keys()
    )

    with INVENTORY_CSV_PATH.open(
        "w",
        encoding="utf-8-sig",
        newline="",
    ) as csv_file:
        writer = csv.DictWriter(
            csv_file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        writer.writerows(
            rows
        )


def build_report(
    rows: Sequence[Dict[str, object]],
) -> str:
    expected_rows = [
        row
        for row in rows
        if row[
            "category"
        ] != "additional"
    ]

    additional_rows = [
        row
        for row in rows
        if row[
            "category"
        ] == "additional"
    ]

    required_rows = [
        row
        for row in expected_rows
        if int(
            row[
                "required"
            ]
        ) == 1
    ]

    optional_rows = [
        row
        for row in expected_rows
        if int(
            row[
                "required"
            ]
        ) == 0
    ]

    missing_required = [
        row
        for row in required_rows
        if row[
            "status"
        ] != "PASS"
    ]

    missing_optional = [
        row
        for row in optional_rows
        if row[
            "status"
        ] != "PASS"
    ]

    empty_files = [
        row
        for row in rows
        if row[
            "status"
        ] == "EMPTY"
    ]

    existing_rows = [
        row
        for row in rows
        if int(
            row[
                "exists"
            ]
        ) == 1
    ]

    total_size_bytes = sum(
        int(
            row[
                "size_bytes"
            ]
        )
        for row in existing_rows
    )

    category_counts: Dict[
        str,
        int,
    ] = {}

    for row in existing_rows:
        category = str(
            row[
                "category"
            ]
        )

        category_counts[
            category
        ] = (
            category_counts.get(
                category,
                0,
            )
            + 1
        )

    overall_status = (
        "PASS"
        if not missing_required
        and not empty_files
        else "FAIL"
    )

    lines = [
        "Experiment-results inventory validation",
        "",
        "[SUMMARY]",
        f"Status={overall_status}",
        f"Expected outputs={len(expected_rows)}",
        f"Required outputs={len(required_rows)}",
        (
            "Required outputs present="
            f"{len(required_rows) - len(missing_required)}"
        ),
        f"Optional outputs={len(optional_rows)}",
        (
            "Optional outputs present="
            f"{len(optional_rows) - len(missing_optional)}"
        ),
        f"Additional discovered outputs={len(additional_rows)}",
        f"Existing inventoried files={len(existing_rows)}",
        f"Empty files={len(empty_files)}",
        f"Total inventoried size={human_readable_size(total_size_bytes)}",
        "",
        "[CATEGORY COUNTS]",
    ]

    for category in sorted(
        category_counts
    ):
        lines.append(
            f"{category}={category_counts[category]}"
        )

    lines.extend(
        [
            "",
            "[MISSING REQUIRED OUTPUTS]",
        ]
    )

    if missing_required:
        for row in missing_required:
            lines.append(
                (
                    f"{row['status']}: "
                    f"{row['relative_path']} — "
                    f"{row['description']}"
                )
            )
    else:
        lines.append(
            "None"
        )

    lines.extend(
        [
            "",
            "[MISSING OPTIONAL OUTPUTS]",
        ]
    )

    if missing_optional:
        for row in missing_optional:
            lines.append(
                (
                    f"{row['status']}: "
                    f"{row['relative_path']} — "
                    f"{row['description']}"
                )
            )
    else:
        lines.append(
            "None"
        )

    lines.extend(
        [
            "",
            "[EMPTY FILES]",
        ]
    )

    if empty_files:
        for row in empty_files:
            lines.append(
                str(
                    row[
                        "relative_path"
                    ]
                )
            )
    else:
        lines.append(
            "None"
        )

    lines.extend(
        [
            "",
            "[REQUIRED OUTPUT DETAILS]",
        ]
    )

    for row in required_rows:
        lines.append(
            (
                f"{row['status']}: "
                f"{row['relative_path']}, "
                f"size={row['size_display']}, "
                f"csv_rows={row['csv_data_rows']}"
            )
        )

    lines.extend(
        [
            "",
            "[RECENT RUNTIME OUTPUTS]",
        ]
    )

    for row in expected_rows:
        if row[
            "category"
        ] == "runtime":
            lines.append(
                (
                    f"{row['status']}: "
                    f"{row['relative_path']}, "
                    f"size={row['size_display']}, "
                    f"modified={row['modified_time']}"
                )
            )

    lines.extend(
        [
            "",
            "[OUTPUTS]",
            f"Inventory CSV: {INVENTORY_CSV_PATH}",
            f"Validation report: {REPORT_PATH}",
        ]
    )

    return "\n".join(
        lines
    )


def main() -> None:
    stage(
        "=" * 78
    )

    stage(
        "UPDATE EXPERIMENT RESULTS INVENTORY"
    )

    stage(
        "=" * 78
    )

    stage(
        "[1] Inspect expected outputs"
    )

    expected_rows = [
        inspect_output(
            expected
        )
        for expected in EXPECTED_OUTPUTS
    ]

    stage(
        f"[1] PASS: expected outputs={len(expected_rows)}"
    )

    inventoried_paths = {
        str(
            row[
                "relative_path"
            ]
        )
        for row in expected_rows
    }

    stage(
        "[2] Discover additional result files"
    )

    additional_rows = discover_additional_outputs(
        inventoried_paths
    )

    stage(
        f"[2] PASS: additional outputs={len(additional_rows)}"
    )

    all_rows = (
        expected_rows
        + additional_rows
    )

    all_rows = sorted(
        all_rows,
        key=lambda row: (
            str(
                row[
                    "category"
                ]
            ),
            str(
                row[
                    "relative_path"
                ]
            ),
        ),
    )

    stage(
        "[3] Save inventory CSV"
    )

    save_inventory_csv(
        all_rows
    )

    stage(
        f"[3] PASS: {INVENTORY_CSV_PATH}"
    )

    stage(
        "[4] Generate validation report"
    )

    report_text = build_report(
        all_rows
    )

    REPORT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    REPORT_PATH.write_text(
        report_text,
        encoding="utf-8",
    )

    stage(
        "[4] PASS"
    )

    stage(
        ""
    )

    stage(
        report_text
    )

    stage(
        ""
    )

    required_failures = [
        row
        for row in expected_rows
        if int(
            row[
                "required"
            ]
        ) == 1
        and row[
            "status"
        ] != "PASS"
    ]

    empty_files = [
        row
        for row in all_rows
        if row[
            "status"
        ] == "EMPTY"
    ]

    if required_failures or empty_files:
        stage(
            "=" * 78
        )

        stage(
            "EXPERIMENT RESULTS INVENTORY FAILED"
        )

        stage(
            "=" * 78
        )

        raise SystemExit(
            1
        )

    stage(
        "=" * 78
    )

    stage(
        "EXPERIMENT RESULTS INVENTORY PASSED"
    )

    stage(
        "=" * 78
    )


if __name__ == "__main__":
    main()